/// <reference types="node" />
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { runnerImport, type Plugin } from "vite";
import {
  buildScheme,
  schemeCssFrom,
  type ColorUtilities,
  type SchemeOptions,
  type SchemeSelectors,
  type SchemeVars,
} from "../lib/m3/scheme.ts";

export interface M3SchemeOptions extends Omit<SchemeOptions, "dark"> {
  /**
   * Also writes the stylesheet to this path (relative to the Vite root), so Tailwind can
   * `@import` it after `@solidx/kit/m3/tokens.css`. The file is only rewritten when it changes.
   */
  outFile?: string;
  /**
   * Selectors for the light and dark blocks. The default `:root:root` / `:root.dark` beats the
   * `:root` / `.dark` defaults in tokens.css whatever order the stylesheets load in.
   */
  selectors?: SchemeSelectors;
}

const cssId = "virtual:m3-scheme.css";
const jsId = "virtual:m3-scheme";
const resolvedCssId = `\0${cssId}`;
const resolvedJsId = `\0${jsId}`;

const header = "/* Generated by m3Scheme from @solidx/kit/vite. Do not edit. */\n";

/**
 * Generates the M3 color scheme at build time and overrides the default `--md-sys-color-*`
 * tokens. Import `virtual:m3-scheme.css` from the app entry, or set `outFile` and `@import`
 * the file from CSS. `virtual:m3-scheme` exports the `light` / `dark` vars for `applyScheme`.
 */
export function m3Scheme(options: M3SchemeOptions): Plugin {
  const { outFile, selectors = { light: ":root:root", dark: ":root.dark" }, ...scheme } = options;
  let light: SchemeVars;
  let dark: SchemeVars;
  let css: string;

  return {
    name: "solidx:m3-scheme",
    enforce: "pre",

    async configResolved(config) {
      // color-utilities 0.4.0 has extensionless relative imports that Node's ESM loader rejects.
      // Vite's module runner resolves them.
      const entry = createRequire(import.meta.url).resolve("@material/material-color-utilities");
      const { module: utilities } = await runnerImport<ColorUtilities>(entry, {
        root: config.root,
        logLevel: "silent",
        environments: { inline: { resolve: { noExternal: true } } },
      });
      light = buildScheme(utilities, { ...scheme, dark: false });
      dark = buildScheme(utilities, { ...scheme, dark: true });
      css = schemeCssFrom(light, dark, selectors);

      if (outFile) {
        const file = resolve(config.root, outFile);
        const content = header + css;
        const current = await readFile(file, "utf8").catch(() => undefined);
        if (current !== content) {
          await mkdir(dirname(file), { recursive: true });
          await writeFile(file, content);
        }
      }
    },

    resolveId(id) {
      if (id === cssId) return resolvedCssId;
      if (id === jsId) return resolvedJsId;
    },

    load(id) {
      if (id === resolvedCssId) return css;
      if (id === resolvedJsId) {
        return [
          `export const options = ${JSON.stringify(scheme)};`,
          `export const light = ${JSON.stringify(light)};`,
          `export const dark = ${JSON.stringify(dark)};`,
        ].join("\n");
      }
    },
  };
}
